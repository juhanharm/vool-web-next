#!/usr/bin/env python3
"""Regenerate public/admin/config.yml (the site editor's form definitions) from the page data.
Run after adding a new kind of section or a new field:  python3 scripts/make_editor_config.py"""
import json, glob, yaml
pages = [json.load(open(f)) for f in sorted(glob.glob('src/content/pages-json/*.json'))]
LABEL = {'cta': 'Buttons', 'q': 'Question', 'a': 'Answer', 'href': 'Link', 'alt': 'Image description', 'cols': 'Columns', 'soft': 'Grey background', 'dark': 'Dark background', 'flip': 'Image on the right', 'more': 'Link text', 'lead': 'Intro text', 'eyebrow': 'Small label above the title', 'rows': 'Rows', 'head': 'Column headings', 'cells': 'Cells'}
lab = lambda k: LABEL.get(k, k.replace('_', ' ').capitalize())
def field(name, vals):
    vals = [v for v in vals if v is not None]
    f = {'name': name, 'label': lab(name), 'required': False}
    v0 = vals[0] if vals else ''
    if isinstance(v0, bool): f['widget'] = 'boolean'
    elif isinstance(v0, (int, float)): f.update(widget='number', value_type='float')
    elif isinstance(v0, str):
        long = any(len(v) > 70 or '\n' in v for v in vals if isinstance(v, str))
        f['widget'] = 'image' if name in ('image', 'src') else ('text' if long else 'string')
    elif isinstance(v0, list):
        items = [i for v in vals for i in v]
        if items and isinstance(items[0], dict):
            f.update(widget='list', fields=fields_of(items), summary='{{title}}{{label}}{{q}}{{name}}')
        else:
            f['widget'] = 'list'
            f['field'] = {'name': 'value', 'label': 'Text', 'widget': 'text' if any(isinstance(i, str) and len(i) > 70 for i in items) else 'string'}
    elif isinstance(v0, dict): f.update(widget='object', fields=fields_of(vals), collapsed=True)
    return f
def fields_of(objs):
    keys = []
    for o in objs:
        for k in o:
            if k not in keys: keys.append(k)
    return [field(k, [o.get(k) for o in objs if k in o]) for k in keys]
TYPE_LABEL = {'hero': 'Top banner', 'cards': 'Cards', 'split': 'Text with image', 'steps': 'Numbered steps', 'specs': 'Specification table', 'links': 'Link list', 'faq': 'Questions and answers', 'cta': 'Call to action', 'form': 'Form', 'stats': 'Big numbers', 'logos': 'Logo row', 'night': 'Night charging example', 'cost': 'Cost calculator', 'demo': 'Load management demo', 'table': 'Table', 'prose': 'Text'}
by = {}
for p in pages:
    for s in p['sections']: by.setdefault(s['type'], []).append({k: v for k, v in s.items() if k != 'type'})
types = [{'name': t, 'label': TYPE_LABEL.get(t, t), 'widget': 'object', 'summary': '{{title}}', 'fields': fields_of(v)} for t, v in by.items()]
cfg = yaml.safe_load(open('public/admin/config.yml'))
for c in cfg['collections']:
    if c['name'] == 'pages':
        for f in c['fields']:
            if f['name'] == 'sections': f['types'] = types
open('public/admin/config.yml', 'w').write('# Section forms are generated by scripts/make_editor_config.py from the page data.\n' + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=160))
print(len(types), 'section types')
